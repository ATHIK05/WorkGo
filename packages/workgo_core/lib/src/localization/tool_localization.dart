  /// Translates a tool or equipment name into the specified [localeCode].
  ///
  /// Features:
  /// 1. Exact match against dictionary.
  /// 2. Parenthesized technical spec preservation (e.g. `Digital Multimeter (CAT III)` -> `ഡിജിറ്റൽ മൾട്ടിമീറ്റർ (CAT III)`).
  /// 3. Keyword / category fallback translation.
  /// 4. Graceful fallback to original string.
  static String translate(String toolName, String localeCode) {
    if (toolName.trim().isEmpty) return toolName;
    final targetLocale = localeCode.trim().toLowerCase();
    if (targetLocale == 'en' || targetLocale.isEmpty) return toolName;

    final trimmed = toolName.trim();
    final lowerKey = trimmed.toLowerCase();

    // 1. Direct exact lookup
    if (_exactTranslations.containsKey(lowerKey)) {
      final trans = _exactTranslations[lowerKey]!;
      if (trans.containsKey(targetLocale)) {
        return trans[targetLocale]!;
      }
      if (trans.containsKey('en')) {
        return trans['en']!;
      }
    }

    // 2. Parenthesized technical specification extraction
    // e.g. "Digital Multimeter (CAT III)" or "Pipe Wrench (12" & 14")"
    final parenMatch = RegExp(r'^(.+?)\s*(\([^)]+\))$').firstMatch(trimmed);
    if (parenMatch != null) {
      final base = parenMatch.group(1)!.trim();
      final spec = parenMatch.group(2)!.trim();
      final translatedBase = translate(base, targetLocale);
      if (translatedBase != base) {
        return '$translatedBase $spec';
      }
    }

    // 3. Keyword fallback matching
    for (final entry in _keywordTranslations.entries) {
      final kw = entry.key;
      if (lowerKey.contains(kw)) {
        final kwTrans = entry.value[targetLocale];
        if (kwTrans != null && kwTrans.isNotEmpty) {
          // If the string is purely that keyword or "Insulated " + kw
          if (lowerKey.startsWith('insulated ') && _exactTranslations.containsKey('insulated $kw')) {
            return _exactTranslations['insulated $kw']![targetLocale] ?? toolName;
          }
        }
      }
    }

    return toolName;
  }
}

/// Extension on [String] providing effortless tool name localization in Flutter widgets.
extension DynamicToolLocalization on String {
  /// Translates this trade tool or material string into the user's active locale.
  ///
  /// Example:
  /// ```dart
  /// Text(item.name.toLocalizedTool(context))
  /// ```
  String toLocalizedTool([BuildContext? context]) {
    String localeCode = 'en';

    if (context != null) {
      try {
        final cur = EasyLocalization.of(context)?.currentLocale;
        if (cur != null && cur.languageCode.isNotEmpty) {
          localeCode = cur.languageCode.toLowerCase();
        }
      } catch (_) {}
    }

    if (localeCode == 'en' && WorkGoLocale.currentCode.isNotEmpty && WorkGoLocale.currentCode != 'en') {
      localeCode = WorkGoLocale.currentCode.toLowerCase();
    }

    if (localeCode == 'en') {
      try {
        final curIntl = Intl.defaultLocale ?? Intl.getCurrentLocale();
        if (curIntl.isNotEmpty && curIntl != 'en' && curIntl != 'en_US') {
          localeCode = curIntl.split('_').first.toLowerCase();
        }
      } catch (_) {}
    }

    if (localeCode == 'en') return this;
    return ToolLocalization.translate(this, localeCode);
  }
}
