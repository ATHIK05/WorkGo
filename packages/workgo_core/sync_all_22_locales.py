def sync():
    total_languages = len(dial_karya_translations)
    print(f"Total languages configured in script: {total_languages}")
    assert total_languages == 23, f"Expected 23 languages (en + 22 Indian), got {total_languages}"

    files = [f for f in os.listdir(LANG_DIR) if f.endswith(".json")]
    print(f"Found {len(files)} JSON files in {LANG_DIR}")

    en_keys = dial_karya_translations["en"]
    print(f"Total Dial Karya keys per language: {len(en_keys)}")

    synced_count = 0
    for code, trans in dial_karya_translations.items():
        fname = f"{code}.json"
        fpath = os.path.join(LANG_DIR, fname)
        if not os.path.exists(fpath):
            print(f"WARNING: {fname} does not exist in target dir!")
            continue

        with open(fpath, "r", encoding="utf-8") as f:
            data = json.load(f)

        # Merge new translations
        added = 0
        updated = 0
        for k, v in trans.items():
            if k not in data:
                added += 1
            elif data[k] != v:
                updated += 1
            data[k] = v

        with open(fpath, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)

        print(f"[{code}] {fname}: added {added}, updated {updated}, total keys now {len(data)}")
        synced_count += 1

    print(f"\nSUCCESS: Successfully synced all {synced_count} language files with 100% complete 22-language native translations.")

if __name__ == "__main__":
    sync()
