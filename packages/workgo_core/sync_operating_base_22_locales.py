def sync_operating_base_keys():
    synced = 0
    for code, trans in TRANSLATIONS.items():
        fname = f"{code}.json"
        fpath = os.path.join(LANG_DIR, fname)
        if not os.path.exists(fpath):
            print(f"Skipping {fname} (not found)")
            continue

        with open(fpath, "r", encoding="utf-8") as f:
            try:
                data = json.load(f)
            except Exception as e:
                print(f"Failed to load {fname}: {e}")
                continue

        updated = 0
        added = 0
        for k, v in trans.items():
            if k not in data:
                data[k] = v
                added += 1
            else:
                data[k] = v
                updated += 1

        with open(fpath, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)

        print(f"[{code}] {fname}: Added {added}, updated {updated} keys.")
        synced += 1

    print(f"\nSUCCESS: Synced Operating Base keys across all {synced} language JSON files!")

if __name__ == "__main__":
    sync_operating_base_keys()
