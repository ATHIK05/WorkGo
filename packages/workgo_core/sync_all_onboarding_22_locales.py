def main():
    if not os.path.exists(LANG_DIR):
        print(f"Error: {LANG_DIR} does not exist")
        sys.exit(1)

    files = [f for f in os.listdir(LANG_DIR) if f.endswith(".json")]
    print(f"Found {len(files)} language JSON files in {LANG_DIR}.")

    en_keys = TRANSLATIONS["en"]

    for f in sorted(files):
        lang_code = f.replace(".json", "")
        file_path = os.path.join(LANG_DIR, f)

        try:
            with open(file_path, "r", encoding="utf-8") as fp:
                data = json.load(fp)
        except Exception as e:
            print(f"Error reading {f}: {e}")
            continue

        lang_trans = TRANSLATIONS.get(lang_code, en_keys)
        changed_count = 0

        for key, default_val in en_keys.items():
            val = lang_trans.get(key, default_val)
            if key not in data or data[key] != val:
                data[key] = val
                changed_count += 1

        if changed_count > 0:
            with open(file_path, "w", encoding="utf-8") as fp:
                json.dump(data, fp, ensure_ascii=False, indent=2)
            print(f"Updated {f} with {changed_count} keys.")
        else:
            print(f"No changes needed for {f}.")

    print("Localization sync complete across all 23 language files.")

if __name__ == "__main__":
    main()
