def sync_locales():
    for lang, new_kvs in NEW_TRANSLATIONS.items():
        filepath = os.path.join(LANG_DIR, f"{lang}.json")
        if not os.path.exists(filepath):
            print(f"Skipping {filepath}, does not exist")
            continue
        with open(filepath, "r", encoding="utf-8") as f:
            data = json.load(f)

        # Update and ensure {} is used everywhere instead of {0}
        for k, v in new_kvs.items():
            data[k] = v

        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        print(f"Updated {lang}.json with {len(new_kvs)} keys")

if __name__ == "__main__":
    sync_locales()
