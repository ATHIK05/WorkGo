# Add fallbacks for other remaining scheduled languages (kok, ks, doi, mai, sat, brx, mni, sd)
# mapping to refined local variants or Hindi/English base
REMAINING_LANGUAGES = ["kok", "ks", "doi", "mai", "sat", "brx", "mni", "sd"]

def generate_translations_for_remaining():
    hi_ref = PEER_KYC_TRANSLATIONS["hi"]
    en_ref = PEER_KYC_TRANSLATIONS["en"]

    for code in REMAINING_LANGUAGES:
        base = {}
        source = hi_ref if code in ["mai", "doi", "kok", "sa"] else en_ref
        for k, v in en_ref.items():
            # If Hindi has it and language is North-Indic, prefer Hindi translation; else English
            base[k] = hi_ref.get(k, v) if code in ["mai", "doi", "kok"] else source.get(k, v)
        PEER_KYC_TRANSLATIONS[code] = base

def sync_peer_kyc_keys():
    generate_translations_for_remaining()

    en_keys = PEER_KYC_TRANSLATIONS["en"]
    print(f"Total Peer-KYC keys to sync: {len(en_keys)}")

    synced = 0
    for code, trans in PEER_KYC_TRANSLATIONS.items():
        fname = f"{code}.json"
        fpath = os.path.join(LANG_DIR, fname)
        if not os.path.exists(fpath):
            print(f"Skipping {fname} (not found)")
            continue

        with open(fpath, "r", encoding="utf-8") as f:
            try:
                data = json.load(f)
            except Exception as e:
                print(f"Failed to load {fname}: {e}")
                continue

        added = 0
        updated = 0
        for k, v in trans.items():
            if k not in data:
                data[k] = v
                added += 1
            elif not data[k] or data[k] == k:
                data[k] = v
                updated += 1

        with open(fpath, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)

        print(f"[{code}] {fname}: Added {added}, updated {updated} keys. Total: {len(data)}")
        synced += 1

    print(f"\nSUCCESS: Synced Peer-KYC keys across all {synced} language JSON files!")

if __name__ == "__main__":
    sync_peer_kyc_keys()
