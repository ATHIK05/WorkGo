def sync():
    for loc in LOCALES:
        filepath = os.path.join(LANG_DIR, f"{loc}.json")
        if not os.path.exists(filepath):
            print(f"Skipping missing: {filepath}")
            continue
        with open(filepath, "r", encoding="utf-8") as f:
            d = json.load(f)
        
        updated_count = 0
        for k, translations in DATA.items():
            val = translations.get(loc, translations["en"])
            d[k] = val
            updated_count += 1
            
        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(d, f, ensure_ascii=False, indent=2)
        print(f"Updated {loc}.json with {updated_count} keys.")

if __name__ == "__main__":
    sync()
