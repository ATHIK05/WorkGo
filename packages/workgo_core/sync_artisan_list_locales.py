def main():
    updated = 0
    for code, dict_vals in TRANSLATIONS.items():
        file_path = os.path.join(LANG_DIR, f"{code}.json")
        if not os.path.exists(file_path):
            print(f"Skipping {file_path} (not found)")
            continue
        try:
            with open(file_path, "r", encoding="utf-8") as f:
                data = json.load(f)
            
            for k, v in dict_vals.items():
                data[k] = v
                
            with open(file_path, "w", encoding="utf-8") as f:
                json.dump(data, f, ensure_ascii=False, indent=2)
            updated += 1
            print(f"Updated {code}.json with {len(dict_vals)} keys.")
        except Exception as e:
            print(f"Error updating {code}.json: {e}")
            
    print(f"Successfully synchronized {updated} locale files.")

if __name__ == "__main__":
    main()
