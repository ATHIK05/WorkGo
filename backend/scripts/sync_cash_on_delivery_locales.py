OTHER_LANGS = ["kok", "ks", "mai", "ne", "sd", "brx", "doi", "mni", "sat"]

def sync_locales():
    for code, keys in COD_KEYS.items():
        file_path = os.path.join(LANG_DIR, f"{code}.json")
        if not os.path.exists(file_path):
            continue
        with open(file_path, "r", encoding="utf-8") as f:
            data = json.load(f)
        data.update(keys)
        with open(file_path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        print(f"Updated {code}.json with {len(keys)} COD keys.")

    en_keys = COD_KEYS["en"]
    hi_keys = COD_KEYS["hi"]
    for code in OTHER_LANGS:
        file_path = os.path.join(LANG_DIR, f"{code}.json")
        if not os.path.exists(file_path):
            continue
        with open(file_path, "r", encoding="utf-8") as f:
            data = json.load(f)
        base = hi_keys if code in ["kok", "mai", "ne", "doi", "brx"] else en_keys
        for k, v in base.items():
            data[k] = v
        with open(file_path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        print(f"Synced {code}.json with COD keys.")

if __name__ == "__main__":
    sync_locales()
