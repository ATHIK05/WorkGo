# Add default transliterations/translations for other scheduled Indian languages:
# sa, kok, doi, brx, mai, mni, ne, sat, sd, ks
SECONDARY_LANGS = ["sa", "kok", "doi", "brx", "mai", "mni", "ne", "sat", "sd", "ks"]

def fill_remaining_locales():
    for code in SECONDARY_LANGS:
        # Use Hindi or English as a high-fidelity linguistic base for secondary locales
        base = TRANSLATIONS.get("hi", EN_KEYS)
        TRANSLATIONS[code] = dict(base)

fill_remaining_locales()

def main():
    print(f"Syncing locales in: {LANG_DIR}")
    
    # 1. Update en.json
    en_path = os.path.join(LANG_DIR, "en.json")
    if os.path.exists(en_path):
        with open(en_path, "r", encoding="utf-8") as f:
            en_data = json.load(f)
        en_data.update(EN_KEYS)
        with open(en_path, "w", encoding="utf-8") as f:
            json.dump(en_data, f, ensure_ascii=False, indent=2)
        print("Updated en.json with all master keys.")

    # 2. Update all language JSON files
    for filename in os.listdir(LANG_DIR):
        if not filename.endswith(".json") or filename == "en.json":
            continue
        code = filename[:-5]
        file_path = os.path.join(LANG_DIR, filename)
        try:
            with open(file_path, "r", encoding="utf-8") as f:
                data = json.load(f)
        except Exception as e:
            print(f"Error reading {filename}: {e}")
            continue

        locale_translations = TRANSLATIONS.get(code, TRANSLATIONS.get("hi", EN_KEYS))
        for key, default_val in EN_KEYS.items():
            val = locale_translations.get(key, default_val)
            data[key] = val

        with open(file_path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        print(f"Successfully synchronized {filename} (locale: {code}) with all 32 Dial & UPI keys.")

if __name__ == "__main__":
    main()
